import { readFileSync, writeFileSync } from "node:fs";
const source = JSON.parse(readFileSync(new URL("../../data/preprocessed/stadium_locations.json", import.meta.url), "utf8"));
const content = `// Generated by scripts/sync-stadium-locations.mjs. Edit data/preprocessed/stadium_locations.json.\nexport const stadiumLocationAudit = ${JSON.stringify(source, null, 2)} as const;\n`;
const target = new URL("../lib/stadium-locations.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== content) throw new Error("구장 위치 생성본이 원본과 다릅니다. sync-stadium-locations.mjs를 실행해 주세요.");
} else writeFileSync(target, content);
